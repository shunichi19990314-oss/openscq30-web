/**
 * Sound mode migration planner.
 *
 * Ported from openscq30-lib
 * `lib/src/devices/soundcore/common/modules/sound_modes_v2/migration_planner.rs`.
 *
 * Some devices reject sound mode transitions that the official Soundcore app never performs, for
 * example changing the manual noise canceling level while the noise canceling mode is "Adaptive".
 * The planner turns a "from" state into a "to" state as a sequence of single field changes that are
 * each allowed given the value of their parent field.
 *
 * openscq30-lib uses a bidirectional BFS; a plain forward BFS produces an equally valid (shortest)
 * path and is much easier to follow, so that is what is implemented here.
 */

/**
 * A field value tagged with the index of the field it belongs to, mirroring the per struct field
 * enum generated by openscq30-lib's `MigrationSteps` derive macro. Tagging makes values of
 * different fields never compare equal, even when they hold the same raw value.
 */
export interface MigrationValue {
  readonly field: number;
  readonly value: unknown;
}

export function migrationValue(field: number, value: unknown): MigrationValue {
  return { field, value };
}

function valueKey(value: MigrationValue): string {
  return `${value.field}:${JSON.stringify(value.value) ?? String(value.value)}`;
}

export function migrationValuesEqual(a: MigrationValue, b: MigrationValue): boolean {
  return a.field === b.field && JSON.stringify(a.value) === JSON.stringify(b.value);
}

export interface MigrationRequirement {
  /** Index of the parent field. Must be lower than the index of the field it constrains. */
  index: number;
  /** Parent values that allow this field to be changed. */
  values: MigrationValue[];
}

interface MigrationNode {
  index: number;
  requiredParentValues: MigrationValue[];
  childrenIndices: number[];
}

export class MigrationPlanner {
  private readonly nodes: MigrationNode[];

  constructor(requirements: Array<MigrationRequirement | null>) {
    requirements.forEach((requirement, index) => {
      if (requirement && requirement.index >= index) {
        throw new Error(
          `parents should be listed before children, but index ${index} has parent ${requirement.index}`,
        );
      }
    });

    this.nodes = requirements.map((requirement, index) => ({
      index,
      requiredParentValues: requirement?.values ?? [],
      childrenIndices: [],
    }));

    requirements.forEach((requirement, index) => {
      if (requirement) {
        this.nodes[requirement.index].childrenIndices.push(index);
      }
    });
  }

  get size(): number {
    return this.nodes.length;
  }

  /**
   * Returns the shortest sequence of states leading from `from` to `to`, not including `from`.
   * Each consecutive pair of states differs in exactly one field, and the last state equals `to`.
   */
  migrate(from: MigrationValue[], to: MigrationValue[]): MigrationValue[][] {
    if (from.every((value, index) => migrationValuesEqual(value, to[index]))) {
      return [];
    }

    const startKey = from.map(valueKey).join("|");
    const goalKey = to.map(valueKey).join("|");
    const previous = new Map<string, { state: MigrationValue[]; key: string } | null>();
    previous.set(startKey, null);

    const queue: MigrationValue[][] = [from];
    while (queue.length > 0) {
      const current = queue.shift()!;
      const currentKey = current.map(valueKey).join("|");
      if (currentKey === goalKey) {
        return this.reconstruct(previous, currentKey, current);
      }
      for (const next of this.successors(current, to)) {
        const nextKey = next.map(valueKey).join("|");
        if (previous.has(nextKey)) continue;
        previous.set(nextKey, { state: current, key: currentKey });
        queue.push(next);
      }
    }

    throw new Error("no migration path available");
  }

  private reconstruct(
    previous: Map<string, { state: MigrationValue[]; key: string } | null>,
    goalKey: string,
    goalState: MigrationValue[],
  ): MigrationValue[][] {
    const path: MigrationValue[][] = [];
    let currentKey: string | null = goalKey;
    let currentState: MigrationValue[] | null = goalState;
    while (currentKey !== null && currentState !== null) {
      path.unshift(currentState);
      const entry: { state: MigrationValue[]; key: string } | null =
        previous.get(currentKey) ?? null;
      currentKey = entry ? entry.key : null;
      currentState = entry ? entry.state : null;
    }
    // Remove the initial state, matching openscq30-lib.
    path.shift();
    return path;
  }

  private successors(current: MigrationValue[], target: MigrationValue[]): MigrationValue[][] {
    const reachable = this.interestingReachableNodes(current, target);
    const seen = new Set<string>();
    const states: MigrationValue[][] = [];
    for (const { index, value } of reachable) {
      const dedupeKey = `${index}:${valueKey(value)}`;
      if (seen.has(dedupeKey)) continue;
      seen.add(dedupeKey);
      const next = current.slice();
      next[index] = value;
      states.push(next);
    }
    return states;
  }

  /** Nodes that are reachable and are either the target value or a dependency of another field. */
  private interestingReachableNodes(
    current: MigrationValue[],
    target: MigrationValue[],
  ): Array<{ index: number; value: MigrationValue }> {
    const reachable: Array<{ index: number; value: MigrationValue }> = [];
    for (const node of this.nodes) {
      if (node.requiredParentValues.length === 0) {
        if (!migrationValuesEqual(current[node.index], target[node.index])) {
          reachable.push({ index: node.index, value: target[node.index] });
        }
        this.interestingReachableNodesInner(node, current, target, reachable);
      }
    }
    return reachable;
  }

  private interestingReachableNodesInner(
    parent: MigrationNode,
    current: MigrationValue[],
    target: MigrationValue[],
    reachable: Array<{ index: number; value: MigrationValue }>,
  ): void {
    for (const childIndex of parent.childrenIndices) {
      const child = this.nodes[childIndex];
      const parentValue = current[parent.index];
      const requirementMet = child.requiredParentValues.some((value) =>
        migrationValuesEqual(value, parentValue),
      );
      if (requirementMet) {
        // The requirement to change this field is met, so add its target value plus any values
        // that enable changing another field that depends on this one.
        if (!migrationValuesEqual(current[child.index], target[child.index])) {
          reachable.push({ index: child.index, value: target[child.index] });
        }
        this.interestingReachableNodesInner(child, current, target, reachable);
      } else {
        // The requirement is not met, so moving the parent into a required value becomes a
        // reachable state.
        for (const requiredValue of child.requiredParentValues) {
          const alreadyListed = reachable.some(
            (entry) =>
              entry.index === parent.index && migrationValuesEqual(entry.value, requiredValue),
          );
          if (!alreadyListed) {
            reachable.push({ index: parent.index, value: requiredValue });
          }
        }
      }
    }
  }
}

/** Serializes a state array into the struct fields, using the per field tags. */
export function toMigrationState(
  fields: Array<(state: unknown) => MigrationValue>,
  state: unknown,
): MigrationValue[] {
  return fields.map((field) => field(state));
}
